class Food {
  final int id;
  final String name;
  final String category;
  final String description;
  final double price;
  final int calories;
  final int time;
  final bool vegetarian;
  final String emoji;

  Food({
    required this.id,
    required this.name,
    required this.category,
    required this.description,
    required this.price,
    required this.calories,
    required this.time,
    required this.vegetarian,
    required this.emoji,
  });
}
